import { mkdir, readdir, stat, writeFile } from "node:fs/promises";
import path from "node:path";
import sharp from "sharp";

const ROOT = process.cwd();
const SOURCE_DIRS = [path.join(ROOT, "src/assets"), path.join(ROOT, "public")];
const OUTPUT_DIR = path.join(ROOT, "public/responsive");
const MANIFEST_PATH = path.join(ROOT, "src/lib/responsive-image-manifest.ts");
const WIDTHS = [320, 640, 1024];
const QUALITY = 62;
const MAX_VARIANT_BYTES = 120 * 1024;
const INPUT_RE = /\.(png|jpe?g|webp)$/i;
const SKIP_RE = /(^favicon|og-default|placeholder|hero-portrait-\d+)/i;

const slugify = (fileName) =>
  path
    .basename(fileName, path.extname(fileName))
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "");

const walk = async (dir) => {
  const entries = await readdir(dir, { withFileTypes: true });
  const files = await Promise.all(
    entries.map((entry) => {
      const fullPath = path.join(dir, entry.name);
      return entry.isDirectory() ? walk(fullPath) : fullPath;
    }),
  );
  return files.flat();
};

await mkdir(OUTPUT_DIR, { recursive: true });

const sourceFiles = (await Promise.all(SOURCE_DIRS.map(walk)))
  .flat()
  .filter((file) => INPUT_RE.test(file))
  .filter((file) => !file.includes(`${path.sep}responsive${path.sep}`))
  .filter((file) => !SKIP_RE.test(path.basename(file)));

const manifest = {};
const report = [];

for (const file of sourceFiles) {
  const sourceStat = await stat(file);
  const metadata = await sharp(file).metadata();
  if (!metadata.width || !metadata.height || metadata.width < 160) continue;

  const slug = slugify(file);
  const candidateWidths = WIDTHS.filter((width) => width <= metadata.width);
  const widths = candidateWidths.length ? candidateWidths : [metadata.width];
  const variants = [];

  for (const width of widths) {
    const outputName = `${slug}-${width}.webp`;
    const outputPath = path.join(OUTPUT_DIR, outputName);

    let outputStat;
    for (const quality of [QUALITY, 56, 50, 44]) {
      await sharp(file)
        .rotate()
        .resize({ width, withoutEnlargement: true })
        .webp({ quality, effort: 6 })
        .toFile(outputPath);
      outputStat = await stat(outputPath);
      if (outputStat.size <= MAX_VARIANT_BYTES || quality === 44) break;
    }

    variants.push({
      width,
      src: `/responsive/${outputName}`,
      bytes: outputStat.size,
    });
  }

  const current = manifest[slug];
  const largestVariant = variants.at(-1);
  const entry = {
    width: metadata.width,
    height: metadata.height,
    originalBytes: sourceStat.size,
    variants,
  };

  if (!current || sourceStat.size > current.originalBytes) {
    manifest[slug] = entry;
  }

  report.push({
    file: path.relative(ROOT, file),
    originalKB: Math.round(sourceStat.size / 1024),
    largestVariantKB: Math.round((largestVariant?.bytes ?? 0) / 1024),
    variants: variants.map((variant) => `${variant.width}w:${Math.round(variant.bytes / 1024)}KB`).join(", "),
  });
}

const manifestSource = `// Generated by scripts/generate-responsive-images.mjs. Do not edit by hand.
export type ResponsiveImageVariant = {
  width: number;
  src: string;
  bytes: number;
};

export type ResponsiveImageEntry = {
  width: number;
  height: number;
  originalBytes: number;
  variants: ResponsiveImageVariant[];
};

export const responsiveImageManifest = ${JSON.stringify(manifest, null, 2)} as const satisfies Record<string, ResponsiveImageEntry>;
`;

await writeFile(MANIFEST_PATH, manifestSource);

console.table(report.sort((a, b) => b.originalKB - a.originalKB).slice(0, 30));
console.log(`Generated ${Object.keys(manifest).length} responsive image entries in ${path.relative(ROOT, OUTPUT_DIR)}.`);
